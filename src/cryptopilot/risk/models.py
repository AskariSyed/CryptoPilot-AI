"""
CryptoPilot AI - Quantitative Risk Management Domain Models.
Defines typed schemas for mathematical order proposals, circuit breaker telemetry,
and risk gatekeeper evaluation results.
"""

import uuid
from datetime import UTC, datetime

from pydantic import BaseModel, Field, field_validator

from cryptopilot.strategies.base import SignalType


class SizedOrderProposal(BaseModel):
    """
    Mathematically sized order proposal generated by the Risk Engine.
    Fully constrained by 1% risk budget, 30% max allocation, and exchange minimum notional.
    """

    proposal_id: str = Field(default_factory=lambda: str(uuid.uuid4()))
    symbol: str
    action: SignalType = Field(description="Order side: BUY or SELL")
    quantity: float = Field(gt=0.0, description="Base asset order quantity")
    notional_value: float = Field(
        gt=0.0, description="Quote asset notional value: quantity * entry_price"
    )
    entry_price: float = Field(gt=0.0, description="Reference entry price")
    stop_loss_price: float = Field(gt=0.0, description="Stop-loss price protecting risk budget")
    take_profit_price: float | None = Field(default=None, description="Target take-profit price")
    risk_budget_dollars: float = Field(ge=0.0, description="Max dollar loss risked on trade")
    risk_budget_pct: float = Field(ge=0.0, le=0.10, description="Risk budget percentage of equity")
    allocation_pct: float = Field(
        ge=0.0, le=1.0, description="Portfolio equity allocation percentage"
    )
    estimated_fees: float = Field(ge=0.0, description="Estimated round-trip taker commissions")
    rationale: str = Field(description="Detailed mathematical sizing explanation")
    timestamp: datetime = Field(default_factory=lambda: datetime.now(UTC))

    @field_validator("timestamp", mode="after")
    @classmethod
    def ensure_utc(cls, v: datetime) -> datetime:
        if v.tzinfo is None:
            return v.replace(tzinfo=UTC)
        return v


class CircuitBreakerState(BaseModel):
    """Real-time operational status of emergency trading circuit breakers."""

    is_tripped: bool = False
    trip_reason: str | None = None
    tripped_at: datetime | None = None
    resets_at: datetime | None = None
    starting_daily_equity: float = Field(ge=0.0)
    current_daily_loss: float = 0.0
    daily_loss_pct: float = 0.0
    consecutive_losses: int = 0
    emergency_stop: bool = False
    timestamp: datetime = Field(default_factory=lambda: datetime.now(UTC))

    @field_validator("timestamp", mode="after")
    @classmethod
    def ensure_utc(cls, v: datetime) -> datetime:
        if v.tzinfo is None:
            return v.replace(tzinfo=UTC)
        return v


class RiskEvaluationResult(BaseModel):
    """Comprehensive output of the Risk Engine evaluation for an incoming TradeDecision."""

    is_approved: bool
    rejection_reason: str | None = None
    proposal: SizedOrderProposal | None = None
    evaluated_equity: float = Field(ge=0.0)
    risk_budget_dollars: float = Field(ge=0.0)
    position_notional: float = Field(ge=0.0)
    allocation_pct: float = Field(ge=0.0, le=1.0)
    circuit_breaker_active: bool = False
    timestamp: datetime = Field(default_factory=lambda: datetime.now(UTC))

    @field_validator("timestamp", mode="after")
    @classmethod
    def ensure_utc(cls, v: datetime) -> datetime:
        if v.tzinfo is None:
            return v.replace(tzinfo=UTC)
        return v
